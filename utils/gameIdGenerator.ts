export function generateGameId(): string {
  const randomAdjective = ukrainianAdjectives[Math.floor(Math.random() * ukrainianAdjectives.length)];
  const randomNoun = ukrainianNouns[Math.floor(Math.random() * ukrainianNouns.length)];
  
  // Convert to lowercase
  let adjective = randomAdjective.toLowerCase().replace(/\s+/g, '-');
  let noun = randomNoun.toLowerCase().replace(/\s+/g, '-');
  
  return `${adjective} ${noun}`;
}
